#!/bin/bash
# Scans the media folders and rewrites data/media.js. Run after adding/removing files:
#   ./tools/update-media.sh
set -f
cd "$(dirname "$0")/.." || exit 1

list() {
  find "$1" -maxdepth 1 -type f \( $2 \) 2>/dev/null | LC_ALL=C sort | while IFS= read -r f; do
    printf '    "%s",\n' "$(printf '%s' "$f" | sed 's/\\/\\\\/g; s/"/\\"/g')"
  done
}

IMG='-iname *.jpg -o -iname *.jpeg -o -iname *.png -o -iname *.webp'
AUD='-iname *.mp3 -o -iname *.m4a -o -iname *.aac -o -iname *.wav'

{
  echo "// Generated by tools/update-media.sh - do not edit by hand."
  echo "window.MEDIA = {"
  echo "  backgrounds: ["
  list images/background "$IMG"
  echo "  ],"
  echo "  memories: ["
  list images/memories "$IMG"
  echo "  ],"
  echo "  azan: ["
  list azan "$AUD"
  echo "  ]"
  echo "};"
} > data/media.js

echo "Updated data/media.js:"
grep -c '^    "' data/media.js | xargs echo "  total files:"
