#!/bin/bash
# Copies the Samsung home-row app list and its icons from the TV, so Home Frame matches the TV's home screen.
#   ./tools/fetch-home-apps.sh <TV-IP>
# Writes icons/<store-id>.png and data/homeapps.js. Needs Developer Mode on and the Tizen CLI (sdb).
TV="${1:?usage: fetch-home-apps.sh <TV-IP>}"
export PATH="$HOME/tizen-studio/tools:$PATH"
cd "$(dirname "$0")/.." || exit 1
WORK="$(mktemp -d)"
sdb connect "$TV" >/dev/null || exit 1
mkdir -p "$WORK/firstscreen_data"
sdb pull /opt/usr/home/owner/share/voltapps/firstscreen_data "$WORK/firstscreen_data" >/dev/null || { echo "Could not read the TV's home data"; exit 1; }
python3 - "$WORK" <<'PY'
import json, os, re, shutil, sys
base = sys.argv[1]
d = os.path.join(base, 'firstscreen_data')
raw = json.load(open(os.path.join(d, 'makeYourSmartLauncherData.txt'), encoding='utf-8'))
data = json.loads(raw) if isinstance(raw, str) else raw
apps, seen = [], set()
for sec in data['rsp']['launcher']:
    for a in sec.get('apps', []):
        if a['appId'] in seen: continue
        seen.add(a['appId'])
        apps.append({'id': a['appId'], 'name': a['title']})
os.makedirs('icons', exist_ok=True)
icons = os.path.join(d, 'edenRecommendedAssist')
files = os.listdir(icons) if os.path.isdir(icons) else []
out = []
for a in apps:
    best = None
    for f in files:
        m = re.match(r'^%sicon_(\d+)x\d+_' % re.escape(a['id']), f)
        if m and (best is None or int(m.group(1)) > best[0]): best = (int(m.group(1)), f)
    if best:
        shutil.copy(os.path.join(icons, best[1]), 'icons/%s.png' % a['id'])
    out.append(a)
    print(('  ok   ' if best else '  no icon  ') + a['id'] + '  ' + a['name'])
open('data/homeapps.js', 'w', encoding='utf-8').write('// Generated by tools/fetch-home-apps.sh\nwindow.HOMEAPPS = ' + json.dumps(out, ensure_ascii=False, indent=2) + ';\n')
PY
rm -rf "$WORK"
